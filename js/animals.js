function animalSelectHtml(selected, extraAttrs) {
  const attrs = extraAttrs || "";
  const groups = ANIMAL_GROUPS.map((g) => {
    const opts = g.items
      .map(([emoji, name]) => {
        const sel = emoji === selected ? " selected" : "";
        return `<option value="${emoji}"${sel}>${emoji} ${name}</option>`;
      })
      .join("");
    return `<optgroup label="${g.label}">${opts}</optgroup>`;
  }).join("");
  return `<select class="animal-select" ${attrs}>${groups}</select>`;
}

if (typeof window !== "undefined") {
  window.ANIMAL_GROUPS = ANIMAL_GROUPS;
  window.animalSelectHtml = animalSelectHtml;
}
